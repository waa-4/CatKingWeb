create table if not exists public.threads (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 100),
  body text not null check (char_length(body) between 1 and 10000),
  author_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null check (char_length(author_name) between 1 and 24),
  created_at timestamptz not null default now()
);

create table if not exists public.replies (
  id bigint generated by default as identity primary key,
  thread_id bigint not null references public.threads(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 10000),
  author_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null check (char_length(author_name) between 1 and 24),
  created_at timestamptz not null default now()
);

alter table public.threads enable row level security;
alter table public.replies enable row level security;

grant select on public.threads to anon, authenticated;
grant select on public.replies to anon, authenticated;

grant insert on public.threads to authenticated;
grant insert on public.replies to authenticated;

grant usage, select on sequence public.threads_id_seq to authenticated;
grant usage, select on sequence public.replies_id_seq to authenticated;

drop policy if exists "threads are public" on public.threads;
create policy "threads are public"
on public.threads
for select
to anon, authenticated
using (true);

drop policy if exists "signed in users can make threads" on public.threads;
create policy "signed in users can make threads"
on public.threads
for insert
to authenticated
with check ((select auth.uid()) = author_id);

drop policy if exists "replies are public" on public.replies;
create policy "replies are public"
on public.replies
for select
to anon, authenticated
using (true);

drop policy if exists "signed in users can reply" on public.replies;
create policy "signed in users can reply"
on public.replies
for insert
to authenticated
with check ((select auth.uid()) = author_id);

create index if not exists replies_thread_id_idx on public.replies(thread_id);
create index if not exists threads_author_id_idx on public.threads(author_id);
create index if not exists replies_author_id_idx on public.replies(author_id);
